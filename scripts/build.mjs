import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { Script } from 'node:vm';
import { profiles } from '../src/profiles.js';

export const root = fileURLToPath(new URL('../', import.meta.url));
const files = ['core.js', 'modules/canvas.js', 'modules/navigator.js', 'modules/webgl.js',
  'modules/webrtc.js', 'modules/audio.js', 'runtime.js'];

export async function outputs() {
  const { version, license } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  const parts = await Promise.all(files.map(async file => {
    const source = await readFile(join(root, 'src', file), 'utf8');
    // These small modules deliberately use only single-line static imports and named declarations.
    const body = source.replace(/^import .* from ['"].*['"];\r?\n/gm, '')
      .replace(/^export (?=(function|const) )/gm, '');
    if (/^\s*(import|export)\s/m.test(body)) throw new Error(`Unsupported module syntax: ${file}`);
    return `// Source: src/${file}\n${body.trim()}`;
  }));
  const output = new Map();
  for (const config of Object.values(profiles)) {
    const filename = `browser-privacy-core.${config.id}.user.js`;
    const metadata = [
      '// ==UserScript==',
      `// @name         Browser Privacy Core - ${config.name}`,
      '// @namespace    urn:browser-privacy-core',
      '// @homepageURL  https://github.com/NeonTideX/browser-privacy-core',
      '// @supportURL   https://github.com/NeonTideX/browser-privacy-core/issues',
      `// @downloadURL  https://raw.githubusercontent.com/NeonTideX/browser-privacy-core/main/dist/${filename}`,
      `// @updateURL    https://raw.githubusercontent.com/NeonTideX/browser-privacy-core/main/dist/${filename}`,
      `// @version      ${version}`,
      `// @description  ${config.id === 'stable' ? 'Compatibility-first canvas and hardware privacy.' : 'Stronger readback privacy, reduced entropy, and relay-only WebRTC.'}`,
      '// @match        http://*/*',
      '// @match        https://*/*',
      '// @run-at       document-start',
      '// @grant        none',
      '// @inject-into  page',
      `// @license      ${license}`,
      '// ==/UserScript==',
    ].join('\n');
    const script = `${metadata}\n\n// Generated by npm run build. Edit src/ instead.\n(() => {\n'use strict';\n\n${parts.join('\n\n')}\n\nconst CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});\ninstallPrivacyCore(window, CONFIG, ${JSON.stringify(version)});\n})();\n`;
    new Script(script, { filename });
    output.set(filename, script);
  }
  const checksums = [...output].map(([name, body]) =>
    `${createHash('sha256').update(body).digest('hex')}  ${name}`).join('\n') + '\n';
  output.set('SHA256SUMS', checksums);
  return output;
}

export async function build(check = false) {
  const output = await outputs();
  if (!check) await mkdir(join(root, 'dist'), { recursive: true });
  for (const [filename, body] of output) {
    const path = join(root, 'dist', filename);
    if (check) {
      const existing = await readFile(path, 'utf8').catch(() => null);
      if (existing !== body) throw new Error(`Stale output: dist/${filename}. Run npm run build.`);
    } else await writeFile(path, body);
  }
  console.log(check ? 'Generated artifacts match source.' : 'Built Stable and Hardened userscripts with SHA-256 checksums.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await build(process.argv.includes('--check'));
}
